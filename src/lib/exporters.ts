

import * as XLSX from "xlsx";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import type { CellValue, Dataset, DatasetAnalysis } from "../types";
import { fmtNum, formatBytes } from "./dataEngine";

function download(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function cellToCsv(v: CellValue): string {
  if (v === null || v === undefined) return "";
  const s = String(v);
  if (/[",\n]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

export function exportCsv(ds: Dataset) {
  const header = ds.columns.map(cellToCsv).join(",");
  const lines = ds.rows.map((r) => ds.columns.map((c) => cellToCsv(r[c])).join(","));
  const csv = [header, ...lines].join("\n");
  download(new Blob([csv], { type: "text/csv;charset=utf-8;" }), `${ds.fileName}.csv`);
}

export function exportJson(ds: Dataset) {
  const json = JSON.stringify(ds.rows, null, 2);
  download(new Blob([json], { type: "application/json" }), `${ds.fileName}.json`);
}

export function exportXlsx(ds: Dataset) {
  const ws = XLSX.utils.json_to_sheet(ds.rows, { header: ds.columns });
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Data");
  XLSX.writeFile(wb, `${ds.fileName}.xlsx`);
}

function sqlType(v: CellValue): string {
  if (typeof v === "number") return Number.isInteger(v) ? "INTEGER" : "REAL";
  if (typeof v === "boolean") return "BOOLEAN";
  return "TEXT";
}

function sqlIdent(name: string): string {
  return `"${name.replace(/"/g, "").replace(/[^a-zA-Z0-9_]/g, "_")}"`;
}

function sqlValue(v: CellValue): string {
  if (v === null || v === undefined || v === "") return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  return `'${String(v).replace(/'/g, "''")}'`;
}

export function exportSql(ds: Dataset) {
  const table = sqlIdent(ds.fileName.replace(/[^a-zA-Z0-9_]/g, "_") || "dataset");
  const typeSamples: Record<string, string> = {};
  ds.columns.forEach((c) => {
    const sample = ds.rows.find((r) => r[c] !== null && r[c] !== "");
    typeSamples[c] = sample ? sqlType(sample[c]) : "TEXT";
  });
  const createCols = ds.columns.
  map((c) => `  ${sqlIdent(c)} ${typeSamples[c]}`).
  join(",\n");
  const lines: string[] = [
  `-- Generated by Data Analysis Workbench`,
  `-- ${ds.rows.length} rows, ${ds.columns.length} columns`,
  ``,
  `CREATE TABLE IF NOT EXISTS ${table} (`,
  createCols,
  `);`,
  ``];

  const colList = ds.columns.map(sqlIdent).join(", ");
  ds.rows.forEach((r) => {
    const vals = ds.columns.map((c) => sqlValue(r[c])).join(", ");
    lines.push(`INSERT INTO ${table} (${colList}) VALUES (${vals});`);
  });
  download(new Blob([lines.join("\n")], { type: "text/plain;charset=utf-8;" }), `${ds.fileName}.sql`);
}

export function exportParquetNote() {
  const note =
  "Parquet is a columnar binary format that requires a compiled encoder (Apache Arrow) " +
  "not available in this browser workbench.\n\n" +
  "Recommended path: export as CSV or JSON here, then convert with pandas:\n\n" +
  "  import pandas as pd\n" +
  "  df = pd.read_csv('data.csv')\n" +
  "  df.to_parquet('data.parquet')\n";
  download(new Blob([note], { type: "text/plain" }), "parquet_export_instructions.txt");
}

export function exportPdfReport(ds: Dataset, analysis: DatasetAnalysis) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();

  // header band
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, W, 90, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text("Data Quality Report", 40, 45);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(148, 163, 184);
  doc.text(`${ds.fileName}  ·  ${new Date().toLocaleString()}`, 40, 66);

  // score badge
  const score = analysis.qualityScore;
  const scoreColor: [number, number, number] =
  score >= 80 ? [22, 163, 74] : score >= 60 ? [217, 119, 6] : [220, 38, 38];
  doc.setFillColor(...scoreColor);
  doc.roundedRect(W - 130, 28, 90, 36, 6, 6, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont("helvetica", "bold");
  doc.text(`${score}/100`, W - 85, 52, { align: "center" });

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Overview", 40, 120);

  autoTable(doc, {
    startY: 130,
    theme: "grid",
    headStyles: { fillColor: [30, 41, 59] },
    styles: { fontSize: 9 },
    head: [["Metric", "Value"]],
    body: [
    ["Rows", analysis.rowCount.toLocaleString()],
    ["Columns", analysis.columnCount.toLocaleString()],
    ["Total cells", analysis.totalCells.toLocaleString()],
    ["Missing cells", `${analysis.missingCells.toLocaleString()} (${(analysis.missingCells / (analysis.totalCells || 1) * 100).toFixed(1)}%)`],
    ["Duplicate rows", analysis.duplicateRowCount.toLocaleString()],
    ["Memory (est.)", formatBytes(analysis.memoryBytes)],
    ["Completeness", `${analysis.qualityBreakdown.completeness}%`],
    ["Validity", `${analysis.qualityBreakdown.validity}%`],
    ["Uniqueness", `${analysis.qualityBreakdown.uniqueness}%`],
    ["Consistency", `${analysis.qualityBreakdown.consistency}%`]]

  });

  const afterOverview = (doc as unknown as {lastAutoTable: {finalY: number;};}).lastAutoTable.finalY;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Column Profiles", 40, afterOverview + 28);

  autoTable(doc, {
    startY: afterOverview + 38,
    theme: "striped",
    headStyles: { fillColor: [30, 41, 59] },
    styles: { fontSize: 8, cellPadding: 4 },
    head: [["Column", "Type", "Missing", "Unique", "Invalid", "Outliers", "Mean", "Std"]],
    body: analysis.columns.map((c) => [
    c.name,
    c.inferredType,
    String(c.nullCount),
    String(c.uniqueCount),
    String(c.invalidCount),
    String(c.outlierCount),
    c.mean !== undefined ? fmtNum(c.mean) : "—",
    c.std !== undefined ? fmtNum(c.std) : "—"]
    )
  });

  doc.save(`${ds.fileName}_quality_report.pdf`);
}